CREATE TABLE platform.app_user (
    id uuid PRIMARY KEY,
    tenant_id uuid NOT NULL,
    email varchar(320) NOT NULL,
    password_hash varchar(100) NOT NULL,
    display_name varchar(100) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'ACTIVE',
    last_login_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_app_user_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX uq_app_user_email ON platform.app_user (lower(email));
CREATE INDEX ix_app_user_tenant ON platform.app_user (tenant_id);

CREATE TABLE platform.app_role (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(32) NOT NULL UNIQUE,
    name varchar(64) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO platform.app_role(code, name)
VALUES ('USER', 'User'), ('ADMIN', 'Administrator')
ON CONFLICT (code) DO NOTHING;

CREATE TABLE platform.user_role (
    tenant_id uuid NOT NULL,
    user_id uuid NOT NULL REFERENCES platform.app_user(id) ON DELETE CASCADE,
    role_id bigint NOT NULL REFERENCES platform.app_role(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, role_id)
);

CREATE INDEX ix_user_role_tenant ON platform.user_role (tenant_id);

CREATE TABLE platform.invitation (
    id uuid PRIMARY KEY,
    code_prefix varchar(16) NOT NULL,
    code_hash varchar(128) NOT NULL UNIQUE,
    status varchar(20) NOT NULL DEFAULT 'AVAILABLE',
    expires_at timestamptz NOT NULL,
    created_by uuid REFERENCES platform.app_user(id) ON DELETE SET NULL,
    used_by uuid REFERENCES platform.app_user(id) ON DELETE SET NULL,
    used_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_invitation_status CHECK (status IN ('AVAILABLE', 'USED', 'EXPIRED', 'REVOKED')),
    CONSTRAINT ck_invitation_usage CHECK (
        (status = 'USED' AND used_by IS NOT NULL AND used_at IS NOT NULL)
        OR status <> 'USED'
    )
);

CREATE INDEX ix_invitation_lookup ON platform.invitation (status, expires_at);

CREATE TABLE platform.refresh_token (
    id uuid PRIMARY KEY,
    tenant_id uuid NOT NULL,
    user_id uuid NOT NULL REFERENCES platform.app_user(id) ON DELETE CASCADE,
    jti varchar(64) NOT NULL UNIQUE,
    token_hash varchar(128) NOT NULL UNIQUE,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ix_refresh_token_user ON platform.refresh_token (user_id, expires_at);

CREATE TABLE platform.package_plan (
    id uuid PRIMARY KEY,
    code varchar(64) NOT NULL UNIQUE,
    name varchar(100) NOT NULL,
    description text,
    status varchar(20) NOT NULL DEFAULT 'DRAFT',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_package_plan_status CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED'))
);

CREATE TABLE platform.package_plan_version (
    id uuid PRIMARY KEY,
    package_plan_id uuid NOT NULL REFERENCES platform.package_plan(id) ON DELETE RESTRICT,
    version integer NOT NULL,
    price_amount bigint NOT NULL DEFAULT 0,
    currency char(3) NOT NULL DEFAULT 'CNY',
    total_token_quota bigint NOT NULL,
    duration_days integer NOT NULL,
    max_api_keys integer NOT NULL,
    requests_per_minute integer NOT NULL,
    tokens_per_minute bigint NOT NULL,
    max_concurrency integer NOT NULL,
    target_margin_ratio numeric(8, 5) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'DRAFT',
    published_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (package_plan_id, version),
    CONSTRAINT ck_package_version_values CHECK (
        price_amount >= 0 AND total_token_quota > 0 AND duration_days > 0
        AND max_api_keys > 0 AND requests_per_minute > 0
        AND tokens_per_minute > 0 AND max_concurrency > 0
        AND target_margin_ratio >= 0 AND target_margin_ratio < 1
    ),
    CONSTRAINT ck_package_version_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'RETIRED'))
);

CREATE INDEX ix_package_version_status ON platform.package_plan_version (status, published_at DESC);

CREATE TABLE platform.package_plan_version_model (
    id uuid PRIMARY KEY,
    package_plan_version_id uuid NOT NULL REFERENCES platform.package_plan_version(id) ON DELETE CASCADE,
    model_code varchar(128) NOT NULL,
    model_token_quota bigint,
    capabilities jsonb NOT NULL DEFAULT '[]'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (package_plan_version_id, model_code),
    CONSTRAINT ck_model_sub_quota CHECK (model_token_quota IS NULL OR model_token_quota > 0)
);

CREATE TABLE platform.grant_request (
    id uuid PRIMARY KEY,
    business_no varchar(64) NOT NULL UNIQUE,
    tenant_id uuid NOT NULL,
    user_id uuid NOT NULL REFERENCES platform.app_user(id) ON DELETE RESTRICT,
    package_plan_version_id uuid NOT NULL REFERENCES platform.package_plan_version(id) ON DELETE RESTRICT,
    status varchar(24) NOT NULL DEFAULT 'PENDING',
    source varchar(24) NOT NULL DEFAULT 'ADMIN',
    reason varchar(500) NOT NULL,
    created_by uuid REFERENCES platform.app_user(id) ON DELETE SET NULL,
    completed_at timestamptz,
    failure_reason text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_grant_status CHECK (status IN ('PENDING', 'DELIVERING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_grant_source CHECK (source IN ('ADMIN', 'ORDER', 'SYSTEM'))
);

CREATE INDEX ix_grant_user_created ON platform.grant_request (user_id, created_at DESC);

CREATE TABLE platform.customer_order (
    id uuid PRIMARY KEY,
    order_no varchar(64) NOT NULL UNIQUE,
    tenant_id uuid NOT NULL,
    user_id uuid NOT NULL REFERENCES platform.app_user(id) ON DELETE RESTRICT,
    package_plan_version_id uuid NOT NULL REFERENCES platform.package_plan_version(id) ON DELETE RESTRICT,
    amount bigint NOT NULL,
    currency char(3) NOT NULL DEFAULT 'CNY',
    status varchar(24) NOT NULL DEFAULT 'PENDING',
    payment_provider varchar(32) NOT NULL DEFAULT 'MOCK',
    paid_at timestamptz,
    closed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_order_amount CHECK (amount >= 0),
    CONSTRAINT ck_order_status CHECK (status IN ('PENDING', 'PAID', 'CLOSED', 'REFUNDED', 'PARTIALLY_REFUNDED'))
);

CREATE INDEX ix_order_user_created ON platform.customer_order (user_id, created_at DESC);

CREATE TABLE platform.payment_transaction (
    id uuid PRIMARY KEY,
    transaction_no varchar(64) NOT NULL UNIQUE,
    order_id uuid NOT NULL REFERENCES platform.customer_order(id) ON DELETE RESTRICT,
    provider varchar(32) NOT NULL,
    external_trade_no varchar(128),
    amount bigint NOT NULL,
    status varchar(24) NOT NULL DEFAULT 'CREATED',
    callback_hash varchar(128),
    paid_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_payment_amount CHECK (amount >= 0),
    CONSTRAINT ck_payment_status CHECK (status IN ('CREATED', 'PENDING', 'SUCCEEDED', 'FAILED', 'CLOSED'))
);

CREATE UNIQUE INDEX uq_payment_external_trade_no
    ON platform.payment_transaction (provider, external_trade_no)
    WHERE external_trade_no IS NOT NULL;

CREATE TABLE platform.refund (
    id uuid PRIMARY KEY,
    refund_no varchar(64) NOT NULL UNIQUE,
    order_id uuid NOT NULL REFERENCES platform.customer_order(id) ON DELETE RESTRICT,
    payment_transaction_id uuid NOT NULL REFERENCES platform.payment_transaction(id) ON DELETE RESTRICT,
    external_refund_no varchar(128),
    amount bigint NOT NULL,
    status varchar(24) NOT NULL DEFAULT 'PENDING',
    reason varchar(500) NOT NULL,
    completed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_refund_amount CHECK (amount > 0),
    CONSTRAINT ck_refund_status CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED'))
);

CREATE UNIQUE INDEX uq_refund_external_no
    ON platform.refund (external_refund_no)
    WHERE external_refund_no IS NOT NULL;

CREATE TABLE platform.payment_config (
    id uuid PRIMARY KEY,
    provider varchar(32) NOT NULL,
    environment varchar(20) NOT NULL DEFAULT 'LOCAL',
    enabled boolean NOT NULL DEFAULT false,
    encrypted_credentials bytea,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (provider, environment),
    CONSTRAINT ck_payment_environment CHECK (environment IN ('LOCAL', 'SANDBOX', 'PRODUCTION'))
);

CREATE TABLE platform.outbox_event (
    id uuid PRIMARY KEY,
    aggregate_type varchar(64) NOT NULL,
    aggregate_id uuid NOT NULL,
    event_type varchar(128) NOT NULL,
    business_key varchar(128) NOT NULL UNIQUE,
    payload jsonb NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'PENDING',
    attempt_count integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    delivered_at timestamptz,
    last_error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_outbox_status CHECK (status IN ('PENDING', 'DELIVERING', 'DELIVERED', 'FAILED')),
    CONSTRAINT ck_outbox_attempts CHECK (attempt_count >= 0)
);

CREATE INDEX ix_outbox_delivery ON platform.outbox_event (status, next_attempt_at, created_at);

CREATE TABLE platform.admin_audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid,
    actor_user_id uuid REFERENCES platform.app_user(id) ON DELETE SET NULL,
    action varchar(128) NOT NULL,
    resource_type varchar(64) NOT NULL,
    resource_id varchar(128),
    request_id varchar(128),
    outcome varchar(20) NOT NULL,
    detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_audit_outcome CHECK (outcome IN ('SUCCESS', 'FAILURE'))
);

CREATE INDEX ix_audit_actor_created ON platform.admin_audit_log (actor_user_id, created_at DESC);
CREATE INDEX ix_audit_request ON platform.admin_audit_log (request_id) WHERE request_id IS NOT NULL;
