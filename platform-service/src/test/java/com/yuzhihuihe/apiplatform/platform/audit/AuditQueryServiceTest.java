package com.yuzhihuihe.apiplatform.platform.audit;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.sql.DriverManager;
import java.time.Instant;
import java.util.Comparator;
import java.util.List;
import java.util.UUID;

import com.fasterxml.jackson.databind.ObjectMapper;
import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.web.server.ResponseStatusException;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

@Testcontainers
class AuditQueryServiceTest {

    private static final UUID ACTOR_ID = UUID.fromString("71000000-0000-4000-8000-000000000001");
    private static final UUID OTHER_ACTOR_ID = UUID.fromString("71000000-0000-4000-8000-000000000002");

    @Container
    static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:17-alpine");

    private AuditQueryService service;
    private JdbcTemplate jdbcTemplate;

    @BeforeAll
    static void migrate() {
        Flyway.configure()
                .dataSource(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword())
                .defaultSchema("platform")
                .schemas("platform")
                .locations("classpath:db/migration")
                .load()
                .migrate();
        try (var connection = DriverManager.getConnection(
                POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
                var statement = connection.createStatement()) {
            statement.execute("CREATE SCHEMA gateway");
            statement.execute("""
                    CREATE TABLE gateway.admin_operation_audit (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        operation_id uuid NOT NULL UNIQUE,
                        idempotency_key varchar(128) NOT NULL,
                        tenant_id uuid NOT NULL,
                        actor_user_id uuid NOT NULL,
                        action varchar(128) NOT NULL,
                        request_id varchar(128) NOT NULL,
                        status varchar(20) NOT NULL,
                        affected integer,
                        failure_summary varchar(500),
                        created_at timestamptz NOT NULL DEFAULT now(),
                        completed_at timestamptz,
                        updated_at timestamptz NOT NULL DEFAULT now(),
                        resource_type varchar(64) NOT NULL DEFAULT 'GATEWAY_OPERATION',
                        resource_id varchar(128),
                        detail jsonb NOT NULL DEFAULT '{}'::jsonb,
                        UNIQUE (tenant_id, actor_user_id, action, idempotency_key)
                    )
                    """);
        } catch (Exception error) {
            throw new IllegalStateException(error);
        }
    }

    @BeforeEach
    void reset() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
        jdbcTemplate = new JdbcTemplate(dataSource);
        service = new AuditQueryService(
                new AuditQueryRepository(jdbcTemplate), new ObjectMapper());
        jdbcTemplate.update("TRUNCATE platform.admin_audit_log, platform.refresh_token, "
                + "platform.user_role, platform.invitation, platform.app_user RESTART IDENTITY CASCADE");
        jdbcTemplate.update("TRUNCATE gateway.admin_operation_audit RESTART IDENTITY");
        jdbcTemplate.update("""
                INSERT INTO platform.app_user(id, tenant_id, email, password_hash, display_name, status)
                VALUES (?, ?, 'admin@example.com', 'hash', 'Admin', 'ACTIVE'),
                       (?, ?, 'other@example.com', 'hash', 'Other', 'ACTIVE')
                """, ACTOR_ID, ACTOR_ID, OTHER_ACTOR_ID, OTHER_ACTOR_ID);
        jdbcTemplate.update("""
                INSERT INTO platform.admin_audit_log(
                    tenant_id, actor_user_id, action, resource_type, resource_id,
                    request_id, outcome, detail, created_at)
                VALUES (?, ?, 'PACKAGE_GRANT_CREATED', 'GRANT', 'grant-1',
                        'req-audit-1', 'SUCCESS',
                        '{"businessNo":"grant-1","apiKey":"sk-yzh-secret",
                          "nested":{"providerSecret":"provider-secret","safe":"visible"}}',
                        now() - interval '2 minutes'),
                       (?, ?, 'CHANNEL_UPDATED', 'CHANNEL', 'channel-1',
                        'req-audit-2', 'FAILURE', '{"reason":"validation"}',
                        now() - interval '1 minute'),
                       (?, ?, 'PACKAGE_GRANT_CREATED', 'GRANT', 'grant-other',
                        'req-audit-3', 'SUCCESS', '{}', now())
                """, ACTOR_ID, ACTOR_ID, ACTOR_ID, ACTOR_ID, OTHER_ACTOR_ID, OTHER_ACTOR_ID);
        jdbcTemplate.update("""
                INSERT INTO gateway.admin_operation_audit(
                    operation_id, idempotency_key, tenant_id, actor_user_id,
                    action, request_id, status, affected, completed_at)
                VALUES (?, 'idem-recover-audit', ?, ?, 'GATEWAY_RESERVATIONS_RECOVERED',
                    'req-recover-audit', 'COMPLETED', 4, now())
                """, UUID.randomUUID(), ACTOR_ID, ACTOR_ID);
    }

    @Test
    void filtersAndPaginatesAuditRows() {
        AuditQueryService.PageResult<AuditQueryService.AuditEntry> page = service.query(
                new AuditQueryService.PageRequest(0, 1), ACTOR_ID,
                "PACKAGE_GRANT_CREATED", "GRANT", null, "SUCCESS", null, null, null, null);

        assertThat(page.total()).isEqualTo(1);
        assertThat(page.items()).singleElement().satisfies(entry -> {
            assertThat(entry.actorUserId()).isEqualTo(ACTOR_ID);
            assertThat(entry.actorUserNo()).startsWith("U");
            assertThat(entry.actorDisplayName()).isEqualTo("Admin");
            assertThat(entry.requestId()).isEqualTo("req-audit-1");
            assertThat(entry.detail().path("businessNo").asText()).isEqualTo("grant-1");
        });
    }

    @Test
    void redactsSensitiveAuditDetailRecursively() {
        AuditQueryService.PageResult<AuditQueryService.AuditEntry> page = service.query(
                new AuditQueryService.PageRequest(0, 20), ACTOR_ID,
                null, null, null, null, Instant.now().minusSeconds(3600),
                Instant.now().plusSeconds(60), null, null);

        AuditQueryService.AuditEntry grant = page.items().stream()
                .filter(entry -> "req-audit-1".equals(entry.requestId()))
                .findFirst().orElseThrow();
        assertThat(grant.detail().path("apiKey").asText()).isEqualTo("[REDACTED]");
        assertThat(grant.detail().path("nested").path("providerSecret").asText())
                .isEqualTo("[REDACTED]");
        assertThat(grant.detail().path("nested").path("safe").asText()).isEqualTo("visible");
        assertThat(grant.detail().toString()).doesNotContain("sk-yzh-secret", "provider-secret");
    }

    @Test
    void includesDurableGatewayOperationAudits() {
        AuditQueryService.PageResult<AuditQueryService.AuditEntry> page = service.query(
                new AuditQueryService.PageRequest(0, 20), ACTOR_ID,
                "GATEWAY_RESERVATIONS_RECOVERED", "GATEWAY_OPERATION",
                null, "SUCCESS", null, null, null, null);

        assertThat(page.total()).isEqualTo(1);
        assertThat(page.items()).singleElement().satisfies(entry -> {
            assertThat(entry.actorUserId()).isEqualTo(ACTOR_ID);
            assertThat(entry.requestId()).isEqualTo("req-recover-audit");
            assertThat(entry.detail().path("affected").asInt()).isEqualTo(4);
            assertThat(entry.detail().path("status").asText()).isEqualTo("COMPLETED");
        });
    }

    @Test
    void exposesGatewayResourceIdentityAndSafeSnapshotDetail() {
        UUID operationId = UUID.randomUUID();
        jdbcTemplate.update("""
                INSERT INTO gateway.admin_operation_audit(
                    operation_id, idempotency_key, tenant_id, actor_user_id,
                    action, request_id, status, affected, completed_at,
                    resource_type, resource_id, detail)
                VALUES (?, 'idem-channel-audit', ?, ?, 'GATEWAY_CHANNEL_UPDATED',
                    'req-channel-audit', 'COMPLETED', 1, now(),
                    'GATEWAY_CHANNEL', 'channel-audit-1',
                    '{"before":{"name":"Old"},"after":{"name":"New"},
                      "credentialChanged":false}')
                """, operationId, ACTOR_ID, ACTOR_ID);

        AuditQueryService.PageResult<AuditQueryService.AuditEntry> page = service.query(
                new AuditQueryService.PageRequest(0, 20), ACTOR_ID,
                "GATEWAY_CHANNEL_UPDATED", "GATEWAY_CHANNEL",
                "channel-audit-1", "SUCCESS", null, null, null, null);

        assertThat(page.total()).isEqualTo(1);
        assertThat(page.items()).singleElement().satisfies(entry -> {
            assertThat(entry.resourceId()).isEqualTo("channel-audit-1");
            assertThat(entry.detail().at("/before/name").asText()).isEqualTo("Old");
            assertThat(entry.detail().at("/after/name").asText()).isEqualTo("New");
            assertThat(entry.detail().path("credentialChanged").asBoolean()).isFalse();
        });
    }

    @Test
    void sortsAuditRowsByAllowlistedColumns() {
        List<String> ascending = service.query(
                        new AuditQueryService.PageRequest(0, 20), ACTOR_ID,
                        null, null, null, null, null, null, "action", "asc")
                .items().stream().map(AuditQueryService.AuditEntry::action).toList();
        List<String> descending = service.query(
                        new AuditQueryService.PageRequest(0, 20), ACTOR_ID,
                        null, null, null, null, null, null, "action", "desc")
                .items().stream().map(AuditQueryService.AuditEntry::action).toList();

        assertThat(ascending).isSorted();
        assertThat(descending).isSortedAccordingTo(Comparator.reverseOrder());
    }

    @Test
    void pagesCollidingCrossSourceAuditIdsWithAStableSourceIdentity() {
        jdbcTemplate.update("""
                UPDATE platform.admin_audit_log
                SET action = 'COLLISION', created_at = TIMESTAMPTZ '2026-01-01 00:00:00Z'
                WHERE id = 1
                """);
        jdbcTemplate.update("""
                UPDATE gateway.admin_operation_audit
                SET action = 'COLLISION',
                    created_at = TIMESTAMPTZ '2026-01-01 00:00:00Z',
                    completed_at = TIMESTAMPTZ '2026-01-01 00:00:00Z'
                WHERE id = 1
                """);

        AuditQueryService.AuditEntry first = service.query(
                new AuditQueryService.PageRequest(0, 1), ACTOR_ID,
                "COLLISION", null, null, null, null, null, "createdAt", "asc")
                .items().getFirst();
        AuditQueryService.AuditEntry second = service.query(
                new AuditQueryService.PageRequest(1, 1), ACTOR_ID,
                "COLLISION", null, null, null, null, null, "createdAt", "asc")
                .items().getFirst();

        assertThat(List.of(first.requestId(), second.requestId()))
                .containsExactly("req-recover-audit", "req-audit-1");
        assertThat(first.source()).isEqualTo("GATEWAY");
        assertThat(second.source()).isEqualTo("PLATFORM");
    }

    @Test
    void rejectsAuditPageOffsetsThatExceedJdbcIntegerRange() {
        assertInvalid(() -> service.query(
                new AuditQueryService.PageRequest(Integer.MAX_VALUE, 100), null,
                null, null, null, null, null, null, null, null));
    }

    @Test
    void rejectsUnknownAuditSortAndDirection() {
        assertInvalid(() -> service.query(
                new AuditQueryService.PageRequest(0, 20), null,
                null, null, null, null, null, null, "tenantId", "asc"));
        assertInvalid(() -> service.query(
                new AuditQueryService.PageRequest(0, 20), null,
                null, null, null, null, null, null, "createdAt", "sideways"));
    }

    private void assertInvalid(org.assertj.core.api.ThrowableAssert.ThrowingCallable action) {
        assertThatThrownBy(action).isInstanceOfSatisfying(ResponseStatusException.class,
                error -> assertThat(error.getStatusCode()).isEqualTo(HttpStatus.UNPROCESSABLE_ENTITY));
    }
}
