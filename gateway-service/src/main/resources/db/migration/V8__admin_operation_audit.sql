CREATE TABLE gateway.admin_operation_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id uuid NOT NULL UNIQUE,
    idempotency_key varchar(128) NOT NULL,
    tenant_id uuid NOT NULL,
    actor_user_id uuid NOT NULL,
    action varchar(128) NOT NULL,
    request_id varchar(128) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'RUNNING',
    affected integer,
    failure_summary varchar(500),
    created_at timestamptz NOT NULL DEFAULT now(),
    completed_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_admin_operation_idempotency
        UNIQUE (tenant_id, actor_user_id, action, idempotency_key),
    CONSTRAINT ck_admin_operation_status
        CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_admin_operation_completion CHECK (
        (status = 'RUNNING' AND completed_at IS NULL)
        OR (status <> 'RUNNING' AND completed_at IS NOT NULL)
    )
);

CREATE INDEX ix_admin_operation_actor_created
    ON gateway.admin_operation_audit (actor_user_id, created_at DESC);
CREATE INDEX ix_admin_operation_request
    ON gateway.admin_operation_audit (request_id);

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'platform_app') THEN
        GRANT SELECT ON gateway.admin_operation_audit TO platform_app;
    END IF;
END
$$;
